export function makeT(lang) {
  const d = T[lang] || T.ja;
  const fb = T.ja;
  return (key, vars) => {
    let s = d[key] !== undefined ? d[key] : fb[key];
    if (s === undefined) return key;
    if (typeof s === 'string' && vars) {
      for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(v);
    }
    return s;
  };
}

export function floorName(lang, f) {
  const d = (T[lang] || T.ja).floor_names;
  const key = String(f).replace(/\.0$/, '');
  return d[key] || (f > 0 ? 'L' + f : 'B' + Math.abs(f));
}
